#!/usr/bin/env python3
"""Generates the model types of the bindings from the JSON Schema of xbuilder.

    codegen.py <schema.json> go     <out file>  # package xbuilder
    codegen.py <schema.json> python <out file>
    codegen.py <schema.json> java   <out dir> <java package>

The schema (see examples/schema.rs) only uses a small subset of JSON Schema:
objects with properties, `$ref`, arrays, string maps, a string enum, nullable
values and the formats date / partial-time / decimal / uint32. Anything else
fails loudly so a model change is never silently mistranslated.

Rust owns the defaults: Go relies on zero values plus `omitempty`, Java on
`null` plus `@JsonInclude(NON_NULL)`, and Python mirrors the schema defaults.
"""

import json
import keyword
import sys
from dataclasses import dataclass, field

HEADER = "Code generated by xhandler-wasm/codegen.py from xhandler.schema.json. DO NOT EDIT."


# --- Schema model -----------------------------------------------------------


@dataclass
class Type:
    """A property type: `kind` is a scalar name, "ref", "array", "map" or "enum"."""

    kind: str
    ref: str | None = None
    item: "Type | None" = None
    nullable: bool = False


@dataclass
class Prop:
    name: str
    type: Type
    required: bool
    default: object
    has_default: bool
    description: str | None


@dataclass
class Model:
    name: str
    description: str | None
    props: list[Prop] = field(default_factory=list)
    enum: list[str] | None = None


def item(t: Type) -> Type:
    assert t.item, t
    return t.item


def ref(t: Type) -> str:
    assert t.ref, t
    return t.ref


def ref_name(ref: str) -> str:
    return ref.removeprefix("#/definitions/")


def parse_type(schema: dict) -> Type:
    if "$ref" in schema:
        return Type("ref", ref=ref_name(schema["$ref"]))
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return parse_type(schema["allOf"][0])
    if "anyOf" in schema:
        options = [s for s in schema["anyOf"] if s != {"type": "null"}]
        if len(options) == 1 and len(schema["anyOf"]) == 2:
            inner = parse_type(options[0])
            inner.nullable = True
            return inner

    types = schema.get("type")
    nullable = isinstance(types, list) and "null" in types
    if isinstance(types, list):
        types = [t for t in types if t != "null"]
        if len(types) != 1:
            raise ValueError(f"unsupported union: {schema}")
        types = types[0]

    fmt = schema.get("format")
    if types == "string":
        kind = {None: "string", "date": "date", "partial-time": "time", "decimal": "decimal"}[fmt]
        return Type(kind, nullable=nullable)
    if types == "integer" and fmt == "uint32":
        return Type("uint32", nullable=nullable)
    if types == "boolean":
        return Type("bool", nullable=nullable)
    if types == "array":
        return Type("array", item=parse_type(schema["items"]), nullable=nullable)
    if types == "object" and schema.get("additionalProperties") == {"type": "string"}:
        return Type("map", item=Type("string"), nullable=nullable)
    raise ValueError(f"unsupported schema: {schema}")


def load(path: str) -> tuple[list[Model], list[str]]:
    """Returns the models (sorted by name) and the document kinds."""
    definitions = json.load(open(path))["definitions"]

    kinds = [variant["properties"]["kind"]["const"] for variant in definitions["Document"]["oneOf"]]
    models = []
    for name, schema in sorted(definitions.items()):
        if name == "Document":
            continue  # each binding writes its own tagged union
        model = Model(name, schema.get("description"))
        if "enum" in schema:
            model.enum = schema["enum"]
        else:
            # A single allOf is a transparent wrapper (Reversion): same fields
            body = definitions[ref_name(schema["allOf"][0]["$ref"])] if "allOf" in schema else schema
            required = set(body.get("required", []))
            for prop_name, prop in body["properties"].items():
                model.props.append(
                    Prop(
                        prop_name,
                        parse_type(prop),
                        prop_name in required,
                        prop.get("default"),
                        "default" in prop,
                        prop.get("description"),
                    )
                )
        models.append(model)
    return models, kinds


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def camel(name: str) -> str:
    p = pascal(name)
    return p[:1].lower() + p[1:]


def comment(text: str | None, prefix: str) -> list[str]:
    return [f"{prefix}{line}".rstrip() for line in text.splitlines()] if text else []


# --- Go ---------------------------------------------------------------------

GO_SCALARS = {
    "string": "string",
    "bool": "bool",
    "uint32": "uint32",
    "decimal": "Decimal",
    "date": "Date",
    "time": "Time",
}


def go_type(t: Type, pointer: bool = False) -> str:
    if t.kind == "array":
        return "[]" + go_type(item(t))
    if t.kind == "map":
        return "map[string]string"
    base = ref(t) if t.kind == "ref" else GO_SCALARS[t.kind]
    return ("*" if pointer else "") + base


def go_field(p: Prop) -> str:
    """`Name Type `json:"..."``: unset values are left out so Rust fills its defaults."""
    t = p.type
    pointer, option = False, ",omitempty"
    if t.nullable:
        # xbuilder treats a null string as an empty one; other optional values
        # need a pointer to tell "unset" from the zero value.
        pointer = t.kind not in ("string", "array", "map")
    elif p.required:
        option = ""
    elif t.kind == "decimal" and p.default not in (None, "0"):
        pointer = True  # e.g. Defaults.igv_tasa: unset means the Rust default
    elif t.kind in ("date", "time"):
        option = ",omitzero"
    elif t.kind in ("ref", "decimal"):
        option = ""  # always sent; the zero value equals the Rust default
    return f'{pascal(p.name)} {go_type(t, pointer)} `json:"{p.name}{option}"`'


def gen_go(models: list[Model], kinds: list[str]) -> str:
    out = [f"// {HEADER}", "", "package xbuilder", ""]
    for m in models:
        out += comment(m.description, "// ")
        if m.enum:
            out += [f"type {m.name} string", "", "const ("]
            out += [f'\t{m.name}{pascal(v)} {m.name} = "{v}"' for v in m.enum]
            out += [")", ""]
            continue
        out.append(f"type {m.name} struct {{")
        for p in m.props:
            out += comment(p.description, "\t// ")
            out.append(f"\t{go_field(p)}")
        out += ["}", ""]
    for kind in kinds:
        out += [f'func ({kind}) Kind() string {{ return "{kind}" }}', ""]
    return "\n".join(out)


# --- Python -----------------------------------------------------------------

PY_SCALARS = {
    "string": "str",
    "bool": "bool",
    "uint32": "int",
    "decimal": "Decimal",
    "date": "date",
    "time": "time",
}


def py_type(t: Type) -> str:
    if t.kind == "array":
        base = f"list[{py_type(item(t))}]"
    elif t.kind == "map":
        base = "dict[str, str]"
    elif t.kind == "ref":
        base = ref(t)
    else:
        base = PY_SCALARS[t.kind]
    return f"{base} | None" if t.nullable else base


def py_default(p: Prop, enums: set[str]) -> str | None:
    """The Python default of a property, or None when it is required."""
    t, value = p.type, p.default
    if t.nullable:
        return "None"
    if p.required and not p.has_default:
        return None
    if t.kind == "array":
        return "Field(default_factory=list)"
    if t.kind == "map":
        return "Field(default_factory=dict)"
    if t.kind == "ref" and t.ref in enums:
        return f"{t.ref}({value!r})"
    if t.kind == "ref":
        return f"Field(default_factory={t.ref})"
    if t.kind == "decimal":
        return f'Decimal("{value}")'
    if t.kind == "date":
        return f'date.fromisoformat("{value}")'
    if t.kind in ("string", "bool", "uint32"):
        return repr(value)
    raise ValueError(f"unsupported default for {p.name}: {value!r}")


def dependency_order(models: list[Model]) -> list[Model]:
    """Models after the ones they reference, as Python evaluates defaults eagerly."""
    by_name = {m.name: m for m in models}
    ordered: dict[str, Model] = {}

    def refs(t: Type):
        if t.kind == "ref":
            yield t.ref
        if t.item:
            yield from refs(t.item)

    visiting: set[str] = set()

    def visit(m: Model) -> None:
        if m.name in ordered or m.name in visiting:
            return  # done, or a self reference (Vehiculo.secundarios)
        visiting.add(m.name)
        for p in m.props:
            for ref in refs(p.type):
                visit(by_name[ref])
        ordered[m.name] = m

    for m in models:
        visit(m)
    return list(ordered.values())


def py_doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    text = text.replace("\\", "\\\\").replace('"""', '\\"""')
    if text.endswith('"'):
        text = text[:-1] + '\\"'
    return comment(f'"""{text}"""', indent)


def gen_python(models: list[Model], kinds: list[str]) -> str:
    enums = {m.name for m in models if m.enum}
    models = dependency_order(models)
    out = [
        f'"""{HEADER}"""',
        "",
        "from __future__ import annotations",
        "",
        "from datetime import date, time",
        "from decimal import Decimal",
        "from enum import Enum",
        "from typing import Union",
        "",
        "from pydantic import BaseModel, ConfigDict, Field",
        "",
        "",
        "class _Model(BaseModel):",
        '    model_config = ConfigDict(extra="forbid", validate_assignment=True)',
        "",
    ]
    for m in models:
        out.append("")
        if m.enum:
            out.append(f"class {m.name}(str, Enum):")
            out += py_doc(m.description, "    ")
            out += [f"    {v.upper()} = {v!r}" for v in m.enum]
            out.append("")
            continue
        out.append(f"class {m.name}(_Model):")
        out += py_doc(m.description, "    ")
        for p in m.props:
            if keyword.iskeyword(p.name):
                raise ValueError(f"python keyword as field name: {p.name}")
            default = py_default(p, enums)
            out.append(f"    {p.name}: {py_type(p.type)}" + (f" = {default}" if default else ""))
            out += py_doc(p.description, "    ")
        out.append("")
    out += ["", f"Document = Union[{', '.join(kinds)}]", '"""Any document xbuilder can enrich and render."""', ""]
    out += [f"DOCUMENT_KINDS = {tuple(kinds)!r}", ""]
    return "\n".join(out)


# --- Java -------------------------------------------------------------------

JAVA_SCALARS = {
    "string": "String",
    "bool": "Boolean",
    "uint32": "Long",
    "decimal": "BigDecimal",
    "date": "LocalDate",
    "time": "LocalTime",
}


def java_type(t: Type) -> str:
    if t.kind == "array":
        return f"List<{java_type(item(t))}>"
    if t.kind == "map":
        return "Map<String, String>"
    return ref(t) if t.kind == "ref" else JAVA_SCALARS[t.kind]


def java_doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    return [f"{indent}/**"] + comment(text.replace("*/", "*&#47;"), f"{indent} * ") + [f"{indent} */"]


def gen_java(models: list[Model], kinds: list[str], package: str) -> dict[str, str]:
    files = {}
    for m in models:
        out = [f"// {HEADER}", f"package {package};", ""]
        if m.enum:
            out += java_doc(m.description, "")
            out += [f"public enum {m.name} {{", f"    {', '.join(m.enum)}", "}", ""]
            files[m.name] = "\n".join(out)
            continue
        out += [
            "import com.fasterxml.jackson.annotation.JsonInclude;",
            "import com.fasterxml.jackson.annotation.JsonProperty;",
            "import java.math.BigDecimal;",
            "import java.time.LocalDate;",
            "import java.time.LocalTime;",
            "import java.util.List;",
            "import java.util.Map;",
            "import lombok.AllArgsConstructor;",
            "import lombok.Builder;",
            "import lombok.Data;",
            "import lombok.NoArgsConstructor;",
            "",
        ]
        out += java_doc(m.description, "")
        implements = " implements Document" if m.name in kinds else ""
        out += [
            "@Data",
            "@Builder(toBuilder = true)",
            "@NoArgsConstructor",
            "@AllArgsConstructor",
            "@JsonInclude(JsonInclude.Include.NON_NULL)",
            f"public class {m.name}{implements} {{",
        ]
        for p in m.props:
            out += java_doc(p.description, "    ")
            out += [f'    @JsonProperty("{p.name}")', f"    private {java_type(p.type)} {camel(p.name)};", ""]
        out[-1:] = ["}", ""]
        files[m.name] = "\n".join(out)
    files["Document"] = "\n".join(
        [
            f"// {HEADER}",
            f"package {package};",
            "",
            "/** Any document xbuilder can enrich and render: " + ", ".join(kinds) + ". */",
            "public interface Document {",
            "    /** The `kind` tag of the document, e.g. {@code Invoice}. */",
            "    default String kind() {",
            "        return getClass().getSimpleName();",
            "    }",
            "}",
            "",
        ]
    )
    return files


def main() -> None:
    schema, lang, out = sys.argv[1:4]
    models, kinds = load(schema)
    if lang == "go":
        open(out, "w").write(gen_go(models, kinds))
    elif lang == "python":
        open(out, "w").write(gen_python(models, kinds))
    elif lang == "java":
        import os

        os.makedirs(out, exist_ok=True)
        for name, source in gen_java(models, kinds, sys.argv[4]).items():
            open(os.path.join(out, f"{name}.java"), "w").write(source)
    else:
        sys.exit(f"unknown language: {lang}")


if __name__ == "__main__":
    main()
