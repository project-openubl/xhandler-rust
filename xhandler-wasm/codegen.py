#!/usr/bin/env python3
"""Generates the model types of the bindings from the JSON Schema of xhandler-wasm.

    codegen.py <schema.json> <package> go     <out file>
    codegen.py <schema.json> <package> python <out file>
    codegen.py <schema.json> <package> java   <out dir> <java package>

<package> is what to generate (see PACKAGES):
- xbuilder: the documents and their defaults, which the bindings send.
- xsender: the answers of the SUNAT services, which the bindings receive.
  They accept fields they don't know, so an older binding keeps reading the
  answers of a newer core.

The schema (see examples/schema.rs) only uses a small subset of JSON Schema:
- objects with properties, `$ref`, arrays, string maps and nullable values
- string enums, optionally named by `x-enum-varnames`
- externally tagged unions: a `oneOf` of objects with a single property,
  generated as a type with one optional member per variant
- the formats date / partial-time / decimal / byte (base64) / uint16 / uint32

Anything else fails loudly so a model change is never silently mistranslated.

Rust owns the defaults: Go relies on zero values plus `omitempty`, Java on
`null` plus `@JsonInclude(NON_NULL)`. Python mirrors the schema defaults, so
its models read like the Rust ones (`list` fields can be appended to).
Every document type carries its `kind` explicitly, so subclasses and proxies
keep it.
"""

import json
import keyword
import os
import re
import sys
from dataclasses import dataclass, field

HEADER = "Code generated by xhandler-wasm/codegen.py from xhandler.schema.json. DO NOT EDIT."

@dataclass
class Package:
    roots: list[str]
    """The properties of the schema's root it generates, with what they reference"""
    lenient: bool
    """Its types accept unknown fields: they are answers of the core"""


PACKAGES = {
    "xbuilder": Package(["document", "defaults"], lenient=False),
    "xsender": Package(["send_file", "verify_ticket", "consult"], lenient=True),
}


# --- Schema model -----------------------------------------------------------


@dataclass
class Type:
    """A property type: `kind` is a scalar name, "ref", "array", "map" or "enum"."""

    kind: str
    ref: str | None = None
    item: "Type | None" = None
    nullable: bool = False


@dataclass
class Prop:
    name: str
    type: Type
    required: bool
    default: object
    has_default: bool
    description: str | None


@dataclass
class EnumValue:
    value: str
    pascal: str
    """e.g. "InProgress" for "EN_PROCESO", from `x-enum-varnames`; else the value"""
    constant: str
    """e.g. "IN_PROGRESS" for "EN_PROCESO"; the value in capitals without names"""


@dataclass
class Model:
    name: str
    description: str | None
    props: list[Prop] = field(default_factory=list)
    enum: list[EnumValue] | None = None


@dataclass
class Schema:
    models: list[Model]
    kinds: list[str]
    """The document types, in the xbuilder package"""
    lenient: bool
    """Accepts unknown fields: the types are answers of the core"""


def item(t: Type) -> Type:
    assert t.item, t
    return t.item


def ref(t: Type) -> str:
    assert t.ref, t
    return t.ref


def ref_name(ref: str) -> str:
    return ref.removeprefix("#/definitions/")


def parse_type(schema: dict) -> Type:
    if "$ref" in schema:
        return Type("ref", ref=ref_name(schema["$ref"]))
    if "allOf" in schema and len(schema["allOf"]) == 1:
        return parse_type(schema["allOf"][0])
    if "anyOf" in schema:
        options = [s for s in schema["anyOf"] if s != {"type": "null"}]
        if len(options) == 1 and len(schema["anyOf"]) == 2:
            inner = parse_type(options[0])
            inner.nullable = True
            return inner

    types = schema.get("type")
    nullable = isinstance(types, list) and "null" in types
    if isinstance(types, list):
        types = [t for t in types if t != "null"]
        if len(types) != 1:
            raise ValueError(f"unsupported union: {schema}")
        types = types[0]

    fmt = schema.get("format")
    if types == "string":
        strings = {None: "string", "date": "date", "partial-time": "time", "decimal": "decimal", "byte": "bytes"}
        if fmt not in strings:
            raise ValueError(f"unsupported string format: {schema}")
        return Type(strings[fmt], nullable=nullable)
    if types == "integer" and fmt in ("uint16", "uint32"):
        return Type(fmt, nullable=nullable)
    if types == "boolean":
        return Type("bool", nullable=nullable)
    if types == "array":
        return Type("array", item=parse_type(schema["items"]), nullable=nullable)
    if types == "object" and schema.get("additionalProperties") == {"type": "string"}:
        return Type("map", item=Type("string"), nullable=nullable)
    raise ValueError(f"unsupported schema: {schema}")


def references(schema: object) -> set[str]:
    """The definitions a schema references directly."""
    if isinstance(schema, dict):
        found = {ref_name(schema["$ref"])} if "$ref" in schema else set()
        return found.union(*(references(v) for v in schema.values()))
    if isinstance(schema, list):
        return set().union(*(references(v) for v in schema))
    return set()


def reachable(root: dict, package: str) -> set[str]:
    """The definitions the package's root properties reference, directly or not."""
    definitions = root["definitions"]
    seen: set[str] = set()
    pending = references([root["properties"][p] for p in PACKAGES[package].roots])
    while pending:
        name = pending.pop()
        if name not in seen:
            seen.add(name)
            pending |= references(definitions[name])
    return seen


def enum_values(name: str, schema: dict) -> list[EnumValue]:
    values = schema["enum"]
    names = schema.get("x-enum-varnames")
    if names is None:
        return [EnumValue(v, pascal(v), v.upper()) for v in values]
    if len(names) != len(values):
        raise ValueError(f"x-enum-varnames of {name} don't match its values")
    # "InProgress" -> "IN_PROGRESS" (an initialism would be split letter by letter)
    return [EnumValue(v, n, re.sub(r"(?<!^)(?=[A-Z])", "_", n).upper()) for v, n in zip(values, names)]


def union_props(name: str, schema: dict) -> list[Prop]:
    """The members of an externally tagged union, e.g. `{"cdr": ...} | {"fault": ...}`."""
    props = []
    for variant in schema["oneOf"]:
        members = variant.get("properties", {})
        if variant.get("type") != "object" or len(members) != 1 or variant.get("required") != list(members):
            raise ValueError(f"unsupported union variant in {name}: {variant}")
        [(prop_name, prop)] = members.items()
        t = parse_type(prop)
        t.nullable = True  # only the answered variant is set
        props.append(Prop(prop_name, t, False, None, False, prop.get("description")))
    return props


def load(path: str, package: str) -> Schema:
    """Returns the models of the package, sorted by name."""
    root = json.load(open(path))
    definitions = root["definitions"]
    unassigned = set(root["properties"]) - {p for package in PACKAGES.values() for p in package.roots}
    if unassigned:
        raise ValueError(f"root properties in no package: {sorted(unassigned)}")
    names = reachable(root, package)
    others = set().union(*(reachable(root, p) for p in PACKAGES if p != package))
    if names & others:
        raise ValueError(f"types in more than one package: {sorted(names & others)}")

    kinds = []
    if "Document" in names:
        kinds = [variant["properties"]["kind"]["const"] for variant in definitions["Document"]["oneOf"]]
    models = []
    for name in sorted(names):
        schema = definitions[name]
        if name == "Document":
            continue  # each binding writes its own tagged union
        model = Model(name, schema.get("description"))
        if "enum" in schema:
            model.enum = enum_values(name, schema)
        elif "oneOf" in schema:
            model.props = union_props(name, schema)
        else:
            # A single allOf is a transparent wrapper (Reversion): same fields
            body = definitions[ref_name(schema["allOf"][0]["$ref"])] if "allOf" in schema else schema
            required = set(body.get("required", []))
            for prop_name, prop in body["properties"].items():
                model.props.append(
                    Prop(
                        prop_name,
                        parse_type(prop),
                        prop_name in required,
                        prop.get("default"),
                        "default" in prop,
                        prop.get("description"),
                    )
                )
        models.append(model)
    return Schema(models, kinds, lenient=PACKAGES[package].lenient)


def pascal(name: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in name.split("_"))


def camel(name: str) -> str:
    p = pascal(name)
    return p[:1].lower() + p[1:]


def comment(text: str | None, prefix: str) -> list[str]:
    return [f"{prefix}{line}".rstrip() for line in text.splitlines()] if text else []


# --- Go ---------------------------------------------------------------------

GO_SCALARS = {
    "string": "string",
    "bool": "bool",
    "uint16": "int",  # HTTP statuses, an int as in net/http
    "uint32": "uint32",
    "decimal": "Decimal",
    "date": "Date",
    "time": "Time",
}

# Go spells initialisms in capitals
GO_INITIALISMS = {"cdr": "CDR", "http": "HTTP"}


def go_name(name: str) -> str:
    return "".join(GO_INITIALISMS.get(part) or pascal(part) for part in name.split("_"))


def go_type(t: Type, pointer: bool = False) -> str:
    if t.kind == "array":
        return "[]" + go_type(item(t))
    if t.kind == "map":
        return "map[string]string"
    if t.kind == "bytes":
        return "[]byte"  # base64 in JSON
    base = ref(t) if t.kind == "ref" else GO_SCALARS[t.kind]
    return ("*" if pointer else "") + base


def go_field(p: Prop) -> str:
    """`Name Type `json:"..."``: unset values are left out so Rust fills its defaults."""
    t = p.type
    pointer, option = False, ",omitempty"
    if t.nullable:
        # A pointer tells "unset" (Rust None) from the zero value
        pointer = t.kind not in ("array", "map", "bytes")
    elif p.required:
        option = ""
    elif t.kind == "decimal" and p.default not in (None, "0"):
        pointer = True  # e.g. Defaults.igv_tasa: unset means the Rust default
    elif t.kind == "date":
        option = ",omitzero"  # e.g. Envio.fecha_traslado: unset, not year 1
    elif t.kind in ("ref", "decimal"):
        option = ""  # always sent; the zero value equals the Rust default
    return f'{go_name(p.name)} {go_type(t, pointer)} `json:"{p.name}{option}"`'


def gen_go(schema: Schema, package: str) -> str:
    out = [f"// {HEADER}", "", f"package {package}", ""]
    for m in schema.models:
        out += comment(m.description, "// ")
        if m.enum:
            out += [f"type {m.name} string", "", "const ("]
            out += [f'\t{m.name}{v.pascal} {m.name} = "{v.value}"' for v in m.enum]
            out += [")", ""]
            continue
        out.append(f"type {m.name} struct {{")
        for p in m.props:
            out += comment(p.description, "\t// ")
            out.append(f"\t{go_field(p)}")
        out += ["}", ""]
    if schema.kinds:
        out += go_documents(schema.kinds)
    return "\n".join(out)


def go_documents(kinds: list[str]) -> list[str]:
    out = []
    for kind in kinds:
        out += [f'func ({kind}) Kind() string {{ return "{kind}" }}', ""]
    out += [
        "// NewDocument returns an empty document of the given kind, e.g. \"Invoice\",",
        "// or false when the kind is unknown.",
        "func NewDocument(kind string) (Document, bool) {",
        "\tswitch kind {",
    ]
    for kind in kinds:
        out += [f'\tcase "{kind}":', f"\t\treturn &{kind}{{}}, true"]
    out += ["\t}", "\treturn nil, false", "}", ""]
    return out


# --- Python -----------------------------------------------------------------

PY_SCALARS = {
    "string": "str",
    "bool": "bool",
    "uint16": "int",
    "uint32": "int",
    "bytes": "Bytes",
    "decimal": "PlainDecimal",
    "date": "date",
    "time": "time",
}


def py_type(t: Type) -> str:
    if t.kind == "array":
        base = f"list[{py_type(item(t))}]"
    elif t.kind == "map":
        base = "dict[str, str]"
    elif t.kind == "ref":
        base = ref(t)
    else:
        base = PY_SCALARS[t.kind]
    return f"{base} | None" if t.nullable else base


def py_default(p: Prop, enums: set[str]) -> str | None:
    """The Python default of a property, or None when it is required."""
    t, value = p.type, p.default
    if t.nullable:
        return "None"
    if p.required and not p.has_default:
        return None
    if t.kind == "array":
        return "Field(default_factory=list)"
    if t.kind == "map":
        return "Field(default_factory=dict)"
    if t.kind == "ref" and t.ref in enums:
        return f"{t.ref}({value!r})"
    if t.kind == "ref":
        return f"Field(default_factory={t.ref})"
    if t.kind == "decimal":
        return f'Decimal("{value}")'
    if t.kind == "date":
        return f'date.fromisoformat("{value}")'
    if t.kind in ("string", "bool", "uint32"):
        return repr(value)
    raise ValueError(f"unsupported default for {p.name}: {value!r}")


def dependency_order(models: list[Model]) -> list[Model]:
    """Models after the ones they reference, as Python evaluates defaults eagerly."""
    by_name = {m.name: m for m in models}
    ordered: dict[str, Model] = {}

    def refs(t: Type):
        if t.kind == "ref":
            yield t.ref
        if t.item:
            yield from refs(t.item)

    visiting: set[str] = set()

    def visit(m: Model) -> None:
        if m.name in ordered or m.name in visiting:
            return  # done, or a self reference (Vehiculo.secundarios)
        visiting.add(m.name)
        for p in m.props:
            for ref in refs(p.type):
                visit(by_name[ref])
        ordered[m.name] = m

    for m in models:
        visit(m)
    return list(ordered.values())


def py_doc(text: str | None, indent: str) -> list[str]:
    if not text:
        return []
    text = text.replace("\\", "\\\\").replace('"""', '\\"""')
    if text.endswith('"'):
        text = text[:-1] + '\\"'
    return comment(f'"""{text}"""', indent)


def gen_python(schema: Schema) -> str:
    kinds = schema.kinds
    enums = {m.name for m in schema.models if m.enum}
    models = dependency_order(schema.models)
    exports = [m.name for m in models] + (["Document", "DOCUMENT_KINDS"] if kinds else [])
    out = [f'"""{HEADER}"""', "", "from __future__ import annotations", ""]
    preamble = PY_LENIENT_PREAMBLE if schema.lenient else PY_PREAMBLE
    out += [line.format(exports=sorted(exports)) if line.startswith("__all__") else line for line in preamble]
    for m in models:
        out.append("")
        if m.enum:
            out.append(f"class {m.name}(str, Enum):")
            out += py_doc(m.description, "    ")
            out += [f"    {v.constant} = {v.value!r}" for v in m.enum]
            out += ["", "    def __str__(self) -> str:", "        return self.value", ""]
            continue
        out.append(f"class {m.name}(_Model):")
        out += py_doc(m.description, "    ")
        if m.name in kinds:
            out.append(f"    kind: ClassVar[str] = {m.name!r}")
        for p in m.props:
            if keyword.iskeyword(p.name):
                raise ValueError(f"python keyword as field name: {p.name}")
            default = py_default(p, enums)
            out.append(f"    {p.name}: {py_type(p.type)}" + (f" = {default}" if default else ""))
            out += py_doc(p.description, "    ")
        out.append("")
    if kinds:
        out += ["", f"Document = Union[{', '.join(kinds)}]", '"""Any document xbuilder can enrich and render."""', ""]
        out += [f"DOCUMENT_KINDS = {tuple(kinds)!r}", ""]
    return "\n".join(out)


# The documents: mutable, and strict so a misspelt field fails
PY_PREAMBLE = [
    "from datetime import date, time",
    "from decimal import Decimal",
    "from enum import Enum",
    "from typing import Annotated, ClassVar, Union",
    "",
    "from pydantic import BaseModel, ConfigDict, Field, PlainSerializer",
    "",
    "__all__ = {exports!r}",
    "",
    "PlainDecimal = Annotated[",
    '    Decimal, PlainSerializer(lambda d: format(d, "f"), return_type=str, when_used="json")',
    "]",
    '"""A Decimal sent as plain text with its scale: "118.00", never "1.18E+2"."""',
    "",
    "",
    "class _Model(BaseModel):",
    '    model_config = ConfigDict(extra="forbid", validate_assignment=True)',
    "",
]

